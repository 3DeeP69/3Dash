// postinstall: small, idempotent fixes to @capacitor/android so the app builds against
// the AndroidX set pinned in android/variables.gradle (no CoordinatorLayout needed:
// the bridge layout is a single full-screen WebView, a FrameLayout does the same job).
import fs from "node:fs";
const base = "node_modules/@capacitor/android/capacitor";
const lay = base + "/src/main/res/layout/capacitor_bridge_layout_main.xml";
const gradle = base + "/build.gradle";
if (fs.existsSync(lay)) {
  const t = fs.readFileSync(lay, "utf8").replace(/androidx\.coordinatorlayout\.widget\.CoordinatorLayout/g, "FrameLayout");
  fs.writeFileSync(lay, t);
}
if (fs.existsSync(gradle)) {
  let t = fs.readFileSync(gradle, "utf8");
  t = t.replace(/classpath 'com\.android\.tools\.build:gradle:[^']+'/, "classpath 'com.android.tools.build:gradle:8.10.1'");
  t = t.replace(/^\s*implementation "androidx\.coordinatorlayout:coordinatorlayout:\$androidxCoordinatorLayoutVersion"\s*$/m, "");
  fs.writeFileSync(gradle, t);
}
console.log("capacitor patched");
// generated by `cap sync`; pin its AGP to the same version as the app
const cdv = "android/capacitor-cordova-android-plugins/build.gradle";
if (fs.existsSync(cdv)) {
  fs.writeFileSync(cdv, fs.readFileSync(cdv, "utf8").replace(/com\.android\.tools\.build:gradle:[0-9.]+/, "com.android.tools.build:gradle:8.10.1"));
}
